/**
 * Standards-compliant QR Code encoder (ISO/IEC 18004, Model 2), byte mode, versions 1–40.
 *
 * Follows the well-known structure of Project Nayuki's reference implementation (MIT):
 * data → Reed–Solomon error correction → block interleaving → function patterns →
 * zig-zag placement → the lowest-penalty of the 8 masks → format/version information.
 * No dependencies; verified by decoding generated codes with OpenCV (see qr-encoder.test.ts).
 */

export type QrEcc = "L" | "M" | "Q" | "H";

const ECC_INDEX: Record<QrEcc, number> = { L: 0, M: 1, Q: 2, H: 3 };
/** Format-information bits for each level (L=01, M=00, Q=11, H=10). */
const ECC_FORMAT_BITS: Record<QrEcc, number> = { L: 1, M: 0, Q: 3, H: 2 };

